import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const require = createRequire(import.meta.url);
const postcss = require("next/node_modules/postcss");
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(projectRoot, "app/globals.css");
const outputPath = resolve(projectRoot, "app/streamer-enjoy-ui.generated.css");
const enjoySeasonal = '.app-shell[data-streamer="nexplay"][data-seasonal="halloween"]';
const enjoyPlain = '.app-shell[data-streamer="nexplay"]';
const sharedStreamers = [
  "lham",
  "holden",
  "top",
  "kim",
  "ivy",
  "william",
  "zen",
  "lily",
  "lilin",
  "miguel",
  "ammy",
  "grace",
];

const source = postcss.parse(await readFile(sourcePath, "utf8"), {
  from: sourcePath,
});
const output = postcss.root();
output.append(
  postcss.comment({
    text: "Generated by scripts/sync-streamer-enjoy-ui.mjs. Every other streamer (Lham, Holden, Top, Kim, Ivy, William, Zen, Lily, Lilin, Miguel, Ammy and Grace) uses Enjoy's Halloween UI; their streamer art and page backgrounds differ. Do not hand-edit.",
  }),
);

source.walkRules((rule) => {
  const matchingSelectors = postcss.list.comma(rule.selector).filter((selector) => {
    const trimmed = selector.trim();
    if (trimmed.startsWith(enjoySeasonal)) {
      // Each streamer owns its distinct generated page background.
      return trimmed !== enjoySeasonal;
    }
    // Enjoy's synchronized yellow/lime CTA blinks are intentionally not
    // seasonal, so include those three scoped rules too.
    return trimmed.startsWith(`${enjoyPlain} .action-`);
  });
  if (matchingSelectors.length === 0) return;

  for (const streamer of sharedStreamers) {
    const seasonal = `.app-shell[data-streamer="${streamer}"][data-seasonal="halloween"]`;
    let clone = rule.clone({
      selector: matchingSelectors
        .map((selector) => selector.replaceAll(enjoySeasonal, seasonal).replaceAll(enjoyPlain, seasonal))
        .join(",\n"),
    });

    for (let parent = rule.parent; parent && parent.type !== "root"; parent = parent.parent) {
      if (parent.type !== "atrule") continue;
      const wrapper = parent.clone({ nodes: [] });
      wrapper.append(clone);
      clone = wrapper;
    }
    output.append(clone);
  }
});

await writeFile(outputPath, `${output.toString()}\n`);
console.log(`Synced Enjoy UI styles for ${sharedStreamers.join(" and ")} to ${outputPath}`);
